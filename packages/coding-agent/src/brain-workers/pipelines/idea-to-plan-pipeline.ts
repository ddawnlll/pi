/**
 * Idea to Plan Pipeline — 25.Q
 *
 * Orchestrates the end-to-end pipeline from idea ingestion through
 * proposal generation to plan synthesis. Connects the Idea Scout
 * Worker (25.K) with the Plan Synthesizer Worker (25.N) via the
 * Worker Handoff Inbox (25.O).
 *
 * Pipeline stages:
 * 1. **Ingest Ideas** — Receives scouted ideas, validates them, and
 *    applies deduplication against recently processed ideas.
 * 2. **Promote to Proposals** — Converts validated ideas into proposals
 *    with evidence references, confidence scoring, and priority ranking.
 *    Ideas below the confidence threshold are recorded but skipped.
 * 3. **Synthesize Plan** — Feeds proposals into the Plan Synthesizer
 *    Worker to produce a structured plan with workstreams, dependencies,
 *    milestones, and resource estimates.
 * 4. **Validate Output** — Validates the generated plan for structural
 *    integrity, completeness, and compliance with policy.
 * 5. **Complete or Fail** — Emits the final plan or a diagnostic with
 *    evidence of where and why the pipeline failed.
 *
 * All autonomous behavior has explicit budget, cooldown, dedup, and
 * stop-condition handling. All failures surface evidence-backed
 * diagnostics rather than silent errors. Closed-loop behavior is gated
 * by approval or safe local execution policy and cannot recurse
 * indefinitely.
 *
 * @packageDocumentation
 */

