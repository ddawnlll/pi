/**
 * A scouted idea as input to the pipeline.
 *
 * Mirrors ScoutedIdea from the idea-scout worker but allows the pipeline
 * to accept ideas from any compatible source.
 */
export interface PipelineIdea {
	/** Unique identifier (UUID v4) */
	id: string;
	/** Short human-readable title */
	title: string;
	/** Detailed description of the idea */
	description: string;
	/** Confidence score (0-1) from the scout */
	confidence: number;
	/** Priority level */
	priority: "low" | "medium" | "high" | "critical";
	/** Tags for categorization */
	tags: string[];
	/** Source references that inspired this idea */
	sourceRefs: Array<{ type: string; id: string; label: string }>;
	/** ISO 8601 timestamp of creation */
	createdAt: string;
	/** Arbitrary metadata */
	metadata: Record<string, unknown>;
}

