// Dedup Tracker
// ---------------------------------------------------------------------------

/**
 * Tracks deduplication state for pipeline inputs.
 *
 * Prevents the pipeline from processing the same idea signature
 * within the configured dedup window.
 */
export class PipelineDedupTracker {
	private history: Map<string, number> = new Map();
	private config: WorkerDedupConfig;

	constructor(config: WorkerDedupConfig) {
		this.config = config;
	}

	/**
	 * Compute a dedup key for an idea.
	 */
	computeKey(idea: PipelineIdea): string {
		// Use title + description hash for dedup
		const content = `${idea.title}|${idea.description}`;
		return createHash("sha256").update(content).digest("hex");
	}

	/**
	 * Check if an idea is a duplicate within the dedup window.
	 *
	 * @param idea - The idea to check.
	 * @returns True if this idea is a duplicate and should be skipped.
	 */
	isDuplicate(idea: PipelineIdea): boolean {
		if (!this.config.enabled) return false;

		const key = this.computeKey(idea);
		const lastSeen = this.history.get(key);
		if (!lastSeen) return false;

		const elapsed = Date.now() - lastSeen;
		return elapsed < this.config.windowMs;
	}

	/**
	 * Record an idea in the dedup history.
	 *
	 * @param idea - The idea to record.
	 */
	record(idea: PipelineIdea): void {
		if (!this.config.enabled) return;

		const key = this.computeKey(idea);
		this.history.set(key, Date.now());

		// Prune old entries beyond the dedup window
		const cutoff = Date.now() - this.config.windowMs;
		for (const [k, ts] of this.history.entries()) {
			if (ts < cutoff) {
				this.history.delete(k);
			}
		}
	}

	/**
	 * Get the current history size.
	 */
	get historySize(): number {
		return this.history.size;
	}

	/**
	 * Clear all dedup history.
	 */
	clear(): void {
		this.history.clear();
	}
}

