/**
 * Validates pipeline output for structural integrity.
 */
export class PipelineValidator {
	/**
	 * Validate a pipeline output for structural issues.
	 *
	 * @param output - The pipeline output to validate.
	 * @returns Array of validation results.
	 */
	validate(output: PipelineOutput): PipelineValidationResult[] {
		const results: PipelineValidationResult[] = [];

		if (!output.workstreams || output.workstreams.length === 0) {
			results.push({
				type: "error",
				component: "workstream",
				message: "No workstreams generated",
				affectedIds: [],
			});
		}

		const wsIds = output.workstreams.map((ws) => ws.id);
		const uniqueWsIds = new Set(wsIds);
		if (uniqueWsIds.size !== wsIds.length) {
			results.push({
				type: "error",
				component: "workstream",
				message: "Duplicate workstream IDs detected",
				affectedIds: wsIds.filter((id, idx, arr) => arr.indexOf(id) !== idx),
			});
		}

		const validWsIds = new Set(output.workstreams.map((ws) => ws.id));
		for (const dep of output.dependencies) {
			if (!validWsIds.has(dep.from)) {
				results.push({
					type: "error",
					component: "dependency",
					message: `Dependency references non-existent source workstream "${dep.from}"`,
					affectedIds: [dep.from],
				});
			}
			if (!validWsIds.has(dep.to)) {
				results.push({
					type: "error",
					component: "dependency",
					message: `Dependency references non-existent target workstream "${dep.to}"`,
					affectedIds: [dep.to],
				});
			}
		}

		// Check batch consistency
		const batchedIds = new Set<string>();
		for (const batch of output.batches) {
			if (!batch.workstreamIds || batch.workstreamIds.length === 0) {
				results.push({
					type: "warning",
					component: "batch",
					message: `Batch ${batch.index} is empty`,
					affectedIds: [],
				});
			}
			for (const wsId of batch.workstreamIds) {
				if (batchedIds.has(wsId)) {
					results.push({
						type: "error",
						component: "batch",
						message: `Workstream "${wsId}" appears in multiple batches`,
						affectedIds: [wsId],
					});
				}
				batchedIds.add(wsId);
			}
		}

		for (const ws of output.workstreams) {
			if (!batchedIds.has(ws.id)) {
				results.push({
					type: "warning",
					component: "batch",
					message: `Workstream "${ws.id}" is not assigned to any batch`,
					affectedIds: [ws.id],
				});
			}
		}

		// Check provenance
		if (output.ideasConsumed.length === 0) {
			results.push({
				type: "warning",
				component: "provenance",
				message: "No ideas were consumed to produce this plan",
				affectedIds: [],
			});
		}
		if (output.proposalsGenerated.length === 0) {
			results.push({
				type: "warning",
				component: "provenance",
				message: "No proposals were generated to produce this plan",
				affectedIds: [],
			});
		}

		return results;
	}

	/**
	 * Check if validation results contain any errors.
	 */
	hasErrors(results: PipelineValidationResult[]): boolean {
		return results.some((r) => r.type === "error");
	}

	/**
	 * Check if validation results contain any warnings.
	 */
	hasWarnings(results: PipelineValidationResult[]): boolean {
		return results.some((r) => r.type === "warning");
	}
}

